export function translateInterfaceLabel(label: string, locale: string): string {
  return locale.startsWith("ar") ? arabicLabels[label] ?? label : label;
}

export function useInterfaceLabel() {
  const { i18n } = useTranslation();
  const language = i18n.resolvedLanguage ?? i18n.language;
  return useCallback((label: string) => translateInterfaceLabel(label, language), [language]);
}
